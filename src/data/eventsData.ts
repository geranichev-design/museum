function toNoonLocal(dateString: string) {
  return new Date(`${dateString}T12:00:00`);
}

export function pickNearest4(items: EventRecord[], referenceDate = new Date()): EventRecord[] {
  const reference = new Date(referenceDate);
  reference.setHours(12, 0, 0, 0);

  return [...items]
    .sort((a, b) => {
      const diffA = Math.abs(toNoonLocal(a.date).getTime() - reference.getTime());
      const diffB = Math.abs(toNoonLocal(b.date).getTime() - reference.getTime());

      if (diffA !== diffB) return diffA - diffB;
      return toNoonLocal(a.date).getTime() - toNoonLocal(b.date).getTime();
    })
    .slice(0, 4);
}
